                    if (input) input.value = data.promo_code;
                } else {
                    // Not eligible (invalid/expired/below minimum order/
                    // already used/no longer this user's first order) - drop
                    // it rather than leave a stale coupon silently applied.
                    localStorage.removeItem("appliedPromoCode");
                    localStorage.removeItem("appliedPromoDiscount");
                    localStorage.removeItem("appliedPromoSubtotal");
                    showCouponMessage(data.message);
                }
                refreshCouponAppliedViews();
            })
            .catch(error => {
                console.error("Error applying promo code:", error);
                showCouponMessage('Something went wrong while applying the coupon. Please try again.');
            });
    }

    // On page load, re-validate any previously applied coupon (cart contents
    // or eligibility may have changed since it was applied) rather than
    // trusting it blindly.
    window.addEventListener("DOMContentLoaded", () => {
        const appliedPromoCode = localStorage.getItem("appliedPromoCode");
        if (appliedPromoCode) {
            applyPromocode(appliedPromoCode);
        }
    });
</script>



